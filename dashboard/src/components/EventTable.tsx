import { Fragment, useState } from "react";
import type { SecurityEvent } from "../types";
import { TIER_LABEL, categoryLabel, parseServerTime, providerLabel, relativeTime, tierOf } from "../lib";

const TIER_ICON = { critical: "▲", elevated: "◆", low: "●" } as const;

export function EventTable({ events }: { events: SecurityEvent[] }) {
  const [open, setOpen] = useState<Set<number>>(new Set());

  function toggle(id: number) {
    setOpen((prev) => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  }

  return (
    <div className="table-wrap">
      <table className="events">
        <thead>
          <tr>
            <th scope="col">Time</th>
            <th scope="col">Risk</th>
            <th scope="col">AI service</th>
            <th scope="col">Client</th>
            <th scope="col">Data types</th>
            <th scope="col" className="num">Findings</th>
            <th scope="col"><span className="sr-only">Details</span></th>
          </tr>
        </thead>
        <tbody>
          {events.map((event) => {
            const tier = tierOf(event.risk_score);
            const expanded = open.has(event.id);
            const when = parseServerTime(event.created_at);
            return (
              <Fragment key={event.id}>
                <tr className={`row row--${tier}`}>
                  <td title={when.toLocaleString()}>{relativeTime(when)}</td>
                  <td>
                    <span className={`badge badge--${tier}`}>
                      <span aria-hidden="true">{TIER_ICON[tier]}</span> {TIER_LABEL[tier]}
                      <span className="badge__score">{event.risk_score}/10</span>
                    </span>
                  </td>
                  <td>
                    <span className="strong">{providerLabel(event.provider)}</span>
                    <span className="muted small"> · {event.surface === "api" ? "API" : "Web app"}</span>
                    <div className="muted small mono">{event.host}</div>
                  </td>
                  <td className="mono">{event.client_ip ?? "—"}</td>
                  <td>
                    <span className="chips">
                      {event.categories.map((c) => (
                        <span key={c} className="chip">{categoryLabel(c)}</span>
                      ))}
                    </span>
                  </td>
                  <td className="num">{event.finding_count}</td>
                  <td className="actions">
                    <button
                      type="button"
                      className="link-btn"
                      aria-expanded={expanded}
                      aria-controls={`event-${event.id}`}
                      onClick={() => toggle(event.id)}
                    >
                      {expanded ? "Hide" : "Why?"}
                    </button>
                  </td>
                </tr>
                {expanded && (
                  <tr id={`event-${event.id}`} className="detail">
                    <td colSpan={7}>
                      {/* Rationale is generated by our own engine and contains no raw secret values,
                          but it is still rendered strictly as text. */}
                      <p>{event.rationale}</p>
                      <p className="muted small">
                        Matched values and prompt text are never stored — only this summary, the data types
                        detected and the number of findings.
                      </p>
                    </td>
                  </tr>
                )}
              </Fragment>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}
