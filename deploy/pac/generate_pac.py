"""Generate the proxy auto-config (PAC) file that routes AI-service traffic to the inspection proxy.

The host list comes from the proxy's own service registry, so the PAC file and the proxy cannot
drift apart. Design choices:
  * Only AI-service hosts are routed to the proxy; everything else goes DIRECT and is never
    intercepted or even seen by the proxy.
  * By default only hosts whose request parser is VERIFIED are included — intercepting traffic we
    cannot yet inspect adds risk and gives false assurance. Use --include-unverified for a pilot.
  * Fail open: "PROXY host:port; DIRECT" means that if the proxy is down, browsers go direct
    instead of losing internet access. (This is a detect-and-alert product, not a gate.)
  * Only https/wss URLs are routed; the services use TLS and nothing else is worth intercepting.

Usage (from the repo root):
  python deploy/pac/generate_pac.py --proxy proxy.corp.example:8080 --out build/proxy.pac
"""

from __future__ import annotations

import argparse
import json
import logging
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "proxy"))

from ai_security_agent.domains import KNOWN_ENDPOINTS  # noqa: E402

logger = logging.getLogger("aisa.pac")

_PROXY_RE = re.compile(r"^[A-Za-z0-9.\-]+:\d{1,5}$")


def monitored_hosts(include_unverified: bool = False) -> list[str]:
    """Hosts to route through the proxy, sorted. A host is included if any of its entries qualifies."""
    hosts = {
        entry.host
        for entry in KNOWN_ENDPOINTS
        if include_unverified or entry.verified
    }
    return sorted(hosts)


def build_pac(proxy: str, hosts: list[str], fail_open: bool = True) -> str:
    """Render the PAC file text. `proxy` must be host:port (validated; it is embedded in JavaScript)."""
    if not _PROXY_RE.match(proxy):
        raise ValueError(f"--proxy must look like host:port, got {proxy!r}")
    route = f"PROXY {proxy}; DIRECT" if fail_open else f"PROXY {proxy}"
    host_list = json.dumps(hosts, indent=4)
    return f"""// AI Security Agent proxy auto-config.
// GENERATED by deploy/pac/generate_pac.py from the proxy's service registry. Do not edit by hand.
// Only the hosts below (and their subdomains) are sent to the inspection proxy; all other traffic is DIRECT.
function FindProxyForURL(url, host) {{
    var scheme = url.substring(0, url.indexOf(":"));
    if (scheme !== "https" && scheme !== "wss") {{
        return "DIRECT";
    }}
    host = host.toLowerCase();
    var monitored = {host_list};
    for (var i = 0; i < monitored.length; i++) {{
        if (host === monitored[i] || dnsDomainIs(host, "." + monitored[i])) {{
            return "{route}";
        }}
    }}
    return "DIRECT";
}}
"""


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--proxy", required=True, help="Inspection proxy as host:port (reachable from clients)")
    parser.add_argument("--out", required=True, type=Path, help="Where to write the PAC file")
    parser.add_argument("--include-unverified", action="store_true",
                        help="Also route hosts whose parsers are not verified (use for a pilot only)")
    parser.add_argument("--fail-closed", action="store_true",
                        help="Drop the DIRECT fallback (clients lose access to these hosts if the proxy is down)")
    args = parser.parse_args()

    hosts = monitored_hosts(args.include_unverified)
    pac = build_pac(args.proxy, hosts, fail_open=not args.fail_closed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(pac, encoding="utf-8", newline="\n")
    logger.info("Wrote %s — %d monitored hosts: %s", args.out, len(hosts), ", ".join(hosts))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
